import json
import os
from pathlib import Path

config = json.loads(os.environ["BOARD_CONFIG"])
mcu = config.get("mcu", "esp32s3")

# (папка_архитектуры, базовый_env_в_meshtastic, плата_platformio)
arch_map = {
    "esp32": ("esp32", "esp32_base", "esp32doit-devkit-v1"),
    "esp32s3": ("esp32s3", "esp32s3_base", "esp32-s3-devkitc-1"),
    "esp32c3": ("esp32c3", "esp32c3_base", "esp32-c3-devkitm-1"),
    "esp32c6": ("esp32c6", "esp32c6_base", "esp32-c6-devkitc-1"),
    "nrf52840": ("nrf52840", "nrf52840_base", "rak4631"),
}

arch_dir, base_env, default_board = arch_map[mcu]
variant_dir = Path(f"meshtastic-src/variants/{arch_dir}/custom_diy_board")
variant_dir.mkdir(parents=True, exist_ok=True)

lines = [
    "// Auto-generated by Meshtastic Web Builder",
    "#pragma once",
    "",
]

# --- 1. Дисплей и Тачскрин ---
screen = config.get("screen", "none")
if screen == "none":
    lines.append("#define HAS_SCREEN 0")
elif screen in ("ssd1306", "sh1106"):
    lines.append("#define HAS_SCREEN 1")
    lines.append("#define USE_SSD1306" if screen == "ssd1306" else "#define USE_SH1106")
    if config.get("i2c_sda"):
        lines.append(f"#define I2C_SDA {config['i2c_sda']}")
    if config.get("i2c_scl"):
        lines.append(f"#define I2C_SCL {config['i2c_scl']}")
elif screen in ("st7789", "st7735", "ili9341"):
    lines.append("#define HAS_SCREEN 1")
    lines.append("#define HAS_TFT 1")
    tft_macro = {
        "st7789": "ST7789_CS",
        "st7735": "ST7735_CS",
        "ili9341": "ILI9341_CS",
    }[screen]
    lines.append(f"#define USE_{screen.upper()}")
    if config.get("tft_cs"):
        lines.append(f"#define {tft_macro} {config['tft_cs']}")
        lines.append(f"#define TFT_CS {config['tft_cs']}")
    if config.get("tft_dc"):
        lines.append(f"#define TFT_DC {config['tft_dc']}")
    if config.get("tft_rst"):
        lines.append(f"#define TFT_RST {config['tft_rst']}")
    if config.get("tft_bl"):
        lines.append(f"#define TFT_BL {config['tft_bl']}")
    if config.get("tft_sck"):
        lines.append(f"#define TFT_SCLK {config['tft_sck']}")
    if config.get("tft_mosi"):
        lines.append(f"#define TFT_MOSI {config['tft_mosi']}")
    if config.get("tft_miso"):
        lines.append(f"#define TFT_MISO {config['tft_miso']}")
    if config.get("tft_width"):
        lines.append(f"#define TFT_WIDTH {config['tft_width']}")
    if config.get("tft_height"):
        lines.append(f"#define TFT_HEIGHT {config['tft_height']}")
elif screen == "eink":
    lines.append("#define HAS_SCREEN 1")
    lines.append("#define USE_EINK")
    if config.get("tft_cs"):
        lines.append(f"#define PIN_EINK_CS {config['tft_cs']}")
    if config.get("tft_dc"):
        lines.append(f"#define PIN_EINK_DC {config['tft_dc']}")
    if config.get("tft_rst"):
        lines.append(f"#define PIN_EINK_RES {config['tft_rst']}")
    if config.get("tft_bl"):
        lines.append(f"#define PIN_EINK_BUSY {config['tft_bl']}")

# Тачскрин
touch = config.get("touch", "none")
if touch != "none":
    lines.append("#define HAS_TOUCHSCREEN 1")
    if touch in ("ft6336", "cst816"):
        lines.append(f"#define TOUCH_SLAVE_ADDRESS {'0x38' if touch == 'ft6336' else '0x15'}")
        if config.get("i2c_sda"):
            lines.append(f"#define I2C_SDA {config['i2c_sda']}")
        if config.get("i2c_scl"):
            lines.append(f"#define I2C_SCL {config['i2c_scl']}")
        if config.get("touch_int"):
            lines.append(f"#define TOUCH_INT {config['touch_int']}")
        if config.get("touch_rst"):
            lines.append(f"#define TOUCH_RST {config['touch_rst']}")
    elif touch == "xpt2046":
        lines.append("#define USE_XPT2046")
        if config.get("touch_cs"):
            lines.append(f"#define TOUCH_CS {config['touch_cs']}")
        if config.get("touch_int"):
            lines.append(f"#define TOUCH_IRQ {config['touch_int']}")

lines.append("")

# --- 2. Периферия: Кнопка, LED, АКБ, GPS ---
if config.get("button_pin"):
    lines.append(f"#define BUTTON_PIN {config['button_pin']}")
    lines.append("#define BUTTON_NEED_PULLUP")
if config.get("led_pin"):
    lines.append(f"#define LED_PIN {config['led_pin']}")
if config.get("battery_pin"):
    lines.append(f"#define BATTERY_PIN {config['battery_pin']}")
    mult = config.get("adc_multiplier") or "2.0"
    lines.append(f"#define ADC_MULTIPLIER {mult}")

if config.get("gps_rx") and config.get("gps_tx"):
    lines.append("#define HAS_GPS 1")
    lines.append(f"#define GPS_RX_PIN {config['gps_rx']}")
    lines.append(f"#define GPS_TX_PIN {config['gps_tx']}")
else:
    lines.append("#define HAS_GPS 0")

lines.append("")

# --- 3. Радиомодули (E22 / E220 / SX126x / SX127x) ---
for macro, key in [
    ("LORA_SCK", "lora_sck"),
    ("LORA_MISO", "lora_miso"),
    ("LORA_MOSI", "lora_mosi"),
    ("LORA_CS", "lora_cs"),
    ("LORA_RESET", "lora_rst"),
]:
    if config.get(key):
        lines.append(f"#define {macro} {config[key]}")

radio = config.get("radio", "e22_900")
if radio in ("e22_900", "e22_400", "e220_llcc68", "sx1262"):
    chip_macro = {
        "e22_900": "USE_SX1262",
        "sx1262": "USE_SX1262",
        "e22_400": "USE_SX1268",
        "e220_llcc68": "USE_LLCC68",
    }[radio]
    lines.append(f"#define {chip_macro}")

    if config.get("lora_dio1"):
        lines.append(f"#define LORA_DIO1 {config['lora_dio1']}")
    if config.get("lora_busy"):
        lines.append(f"#define SX126X_BUSY {config['lora_busy']}")
        lines.append(f"#define LORA_DIO2 {config['lora_busy']}")
    if config.get("lora_rxen"):
        lines.append(f"#define SX126X_RXEN {config['lora_rxen']}")
    if config.get("lora_txen"):
        lines.append(f"#define SX126X_TXEN {config['lora_txen']}")

    if config.get("dio2_rf_switch") == "1":
        lines.append("#define SX126X_DIO2_AS_RF_SWITCH")

    tcxo = config.get("tcxo_voltage", "1.8")
    if tcxo and tcxo != "0":
        lines.append(f"#define SX126X_DIO3_TCXO_VOLTAGE {tcxo}")

    # Ограничение входной мощности для E22-30S (1W модули с внутренним PA)
    if config.get("e22_high_power") == "1":
        lines.append("#define SX126X_MAX_POWER 22")
else:
    lines.append("#define USE_SX1276")
    if config.get("lora_dio0"):
        lines.append(f"#define LORA_DIO0 {config['lora_dio0']}")
    if config.get("lora_dio1"):
        lines.append(f"#define LORA_DIO1 {config['lora_dio1']}")

# Дополнительные пользовательские дефайны
extra = config.get("extra_defines", "").strip()
if extra:
    lines.append("\n// Extra defines")
    lines.append(extra)

(variant_dir / "variant.h").write_text("\n".join(lines) + "\n", encoding="utf-8")

# Для nRF52840 требуется базовый variant.cpp (берём из стандартного diy варианта)
extra_build_flags = ""
if mcu == "nrf52840":
    extra_build_flags = "\n  -I variants/nrf52840/diy/nrf52840_promicro"
    src_cpp = Path("meshtastic-src/variants/nrf52840/diy/nrf52840_promicro/variant.cpp")
    if src_cpp.exists():
        (variant_dir / "variant.cpp").write_text(src_cpp.read_text(encoding="utf-8"), encoding="utf-8")

pio_ini = f"""[env:custom_diy_board]
extends = {base_env}
board = {default_board}
build_flags =
  ${{{base_env}.build_flags}}
  -D PRIVATE_HW
  -I variants/{arch_dir}/custom_diy_board{extra_build_flags}
"""
(variant_dir / "platformio.ini").write_text(pio_ini, encoding="utf-8")
print("Generated variant.h:\n", "\n".join(lines))
